# Builds FreeMyTV.apk without Gradle (PowerShell port of build.sh):
# aapt2 -> javac -> d8 -> zipalign -> apksigner.
$ErrorActionPreference = 'Continue'
# Builds FreeMyTV.apk for Salute TV (Sber) without Gradle: aapt2 -> javac -> d8 -> zipalign -> apksigner.
# Needs JDK 17+ (JAVA_HOME) and the Android SDK (ANDROID_HOME) with build-tools 34 and platform android-34.
$repo = $PSScriptRoot
$sdk = if ($env:ANDROID_HOME) { $env:ANDROID_HOME } elseif ($env:ANDROID_SDK_ROOT) { $env:ANDROID_SDK_ROOT } else { throw "Set ANDROID_HOME (Android SDK)" }
if (-not $env:JAVA_HOME) { throw "Set JAVA_HOME (JDK 17+)" }
$BT = "$sdk\build-tools\34.0.0"
$AJ = "$sdk\platforms\android-34\android.jar"
$JAVAC = "$env:JAVA_HOME\bin\javac.exe"
$JAVA = "$env:JAVA_HOME\bin\java.exe"
$KEYTOOL = "$env:JAVA_HOME\bin\keytool.exe"
$JAR = "$env:JAVA_HOME\bin\jar.exe"

Set-Location $repo
foreach ($t in @("$BT\aapt2.exe", "$AJ", $JAVAC, $KEYTOOL)) {
    if (-not (Test-Path $t)) { throw "missing tool: $t" }
}

# --- config.properties -> Config.java -------------------------------------------------
$cfgPath = Join-Path $repo 'config.properties'
if (-not (Test-Path $cfgPath)) { Copy-Item (Join-Path $repo 'config.example.properties') $cfgPath }
$props = @{}
foreach ($line in [System.IO.File]::ReadAllLines($cfgPath, [System.Text.Encoding]::UTF8)) {
    if ($line -match '^\s*#' -or $line -notmatch '=') { continue }
    $i = $line.IndexOf('=')
    $k = $line.Substring(0, $i).Trim()
    $v = $line.Substring($i + 1).Trim().Trim('"').Trim('\')
    $props[$k] = $v
}
function Prop([string]$k, [string]$def) { if ($props.ContainsKey($k) -and $props[$k] -ne '') { $props[$k] } else { $def } }
$lat = Prop 'latitude' '40.7128'
$lon = Prop 'longitude' '-74.0060'
if ($lat -notmatch '^-?[0-9]+(\.[0-9]+)?$') { throw "latitude must be a number" }
if ($lon -notmatch '^-?[0-9]+(\.[0-9]+)?$') { throw "longitude must be a number" }
$assist = (Prop 'disable_assistant' 'false') -eq 'true'
$crypto = (Prop 'show_crypto' 'true') -eq 'true'
$anim = (Prop 'hide_animation' 'false') -eq 'true'

function Esc([string]$s) { $s.Replace('\', '\\').Replace('"', '\"') }

if (Test-Path (Join-Path $repo 'out')) { Remove-Item (Join-Path $repo 'out') -Recurse -Force }
New-Item -ItemType Directory -Force -Path (Join-Path $repo 'out\gen\io\freemytv'), (Join-Path $repo 'out\classes') | Out-Null

$configJava = @"
package io.freemytv;

/** Generated by build.ps1 from config.properties: edit that file, not this one. */
final class Config {
    private Config() {}

    static final String TMDB_KEY = "$(Esc (Prop 'tmdb_key' ''))";
    static final String WATCHMODE_KEY = "$(Esc (Prop 'watchmode_key' ''))";
    static final String TMDB_REGION = "$(Esc (Prop 'tmdb_region' 'US'))";
    static final String LATITUDE = "$lat";
    static final String LONGITUDE = "$lon";
    static final String CITY = "$(Esc (Prop 'city' ''))";
    static final String LANGUAGE = "$(Esc (Prop 'language' 'auto'))";
    static final String CURRENCY = "$(Esc (Prop 'currency' 'USD'))";
    static final String TEMPERATURE = "$(Esc (Prop 'temperature' 'auto'))";
    static final String HIDE_SERVICES = "$(Esc (Prop 'hide_services' ''))";
    static final boolean DISABLE_ASSISTANT = $($assist.ToString().ToLower());
    static final boolean SHOW_CRYPTO = $($crypto.ToString().ToLower());
    static final boolean HIDE_ANIMATION = $($anim.ToString().ToLower());
}
"@
[System.IO.File]::WriteAllText((Join-Path $repo 'out\gen\io\freemytv\Config.java'), $configJava, (New-Object System.Text.UTF8Encoding($false)))

# --- aapt2 compile / link -------------------------------------------------------------
& "$BT\aapt2.exe" compile --dir (Join-Path $repo 'app\res') -o (Join-Path $repo 'out\res.zip')
if ($LASTEXITCODE -ne 0) { throw "aapt2 compile failed" }
& "$BT\aapt2.exe" link -o (Join-Path $repo 'out\base.apk') -I $AJ --manifest (Join-Path $repo 'app\AndroidManifest.xml') `
    --java (Join-Path $repo 'out\gen') (Join-Path $repo 'out\res.zip') `
    --min-sdk-version 26 --target-sdk-version 33 -A (Join-Path $repo 'app\assets') -0 ttf
if ($LASTEXITCODE -ne 0) { throw "aapt2 link failed" }

# --- fix Windows backslash asset paths ------------------------------------------------
$fixJava = @'
import java.nio.file.*;
import java.util.zip.*;

class FixAssets {
    public static void main(String[] args) throws Exception {
        Path apk = Paths.get(args[0]);
        Path tmp = apk.resolveSibling(apk.getFileName() + ".fixed");
        int renamed = 0;
        try (ZipInputStream in = new ZipInputStream(Files.newInputStream(apk));
             ZipOutputStream out = new ZipOutputStream(Files.newOutputStream(tmp))) {
            for (ZipEntry e; (e = in.getNextEntry()) != null; ) {
                byte[] data = in.readAllBytes();
                String name = e.getName().replace('\\', '/');
                if (!name.equals(e.getName())) renamed++;
                ZipEntry n = new ZipEntry(name);
                if (e.getMethod() == ZipEntry.STORED) {
                    n.setMethod(ZipEntry.STORED);
                    n.setSize(data.length);
                    n.setCompressedSize(data.length);
                    CRC32 crc = new CRC32();
                    crc.update(data);
                    n.setCrc(crc.getValue());
                }
                out.putNextEntry(n);
                out.write(data);
                out.closeEntry();
            }
        }
        if (renamed > 0) Files.move(tmp, apk, StandardCopyOption.REPLACE_EXISTING);
        else Files.delete(tmp);
        System.out.println("FixAssets: renamed " + renamed + " asset paths in " + apk.getFileName());
    }
}
'@
[System.IO.File]::WriteAllText((Join-Path $repo 'out\FixAssets.java'), $fixJava, (New-Object System.Text.UTF8Encoding($false)))
& $JAVA (Join-Path $repo 'out\FixAssets.java') (Join-Path $repo 'out\base.apk')
if ($LASTEXITCODE -ne 0) { throw "FixAssets failed" }

# --- javac ----------------------------------------------------------------------------
$sources = @()
$sources += Get-ChildItem (Join-Path $repo 'app\src') -Recurse -Filter *.java | ForEach-Object { $_.FullName }
$sources += Get-ChildItem (Join-Path $repo 'out\gen') -Recurse -Filter *.java | ForEach-Object { $_.FullName }
$argList = @('-nowarn', '-Xlint:-options', '-source', '8', '-target', '8',
    '-bootclasspath', "$AJ;$BT\core-lambda-stubs.jar", '-classpath', $AJ,
    '-encoding', 'UTF-8', '-d', (Join-Path $repo 'out\classes')) + $sources
& $JAVAC @argList
if ($LASTEXITCODE -ne 0) { throw "javac failed" }

# --- d8 -------------------------------------------------------------------------------
$classFiles = Get-ChildItem (Join-Path $repo 'out\classes') -Recurse -Filter *.class | ForEach-Object { $_.FullName }
$d8args = @('--release', '--min-api', '26', '--lib', $AJ, '--output', (Join-Path $repo 'out')) + $classFiles
& "$BT\d8.bat" @d8args
if ($LASTEXITCODE -ne 0) { throw "d8 failed" }

# --- put classes.dex into the apk ------------------------------------------------------
Push-Location (Join-Path $repo 'out')
try { & $JAR -u -M -f (Join-Path $repo 'out\base.apk') classes.dex } finally { Pop-Location }
if ($LASTEXITCODE -ne 0) { throw "jar update failed" }

# --- zipalign + sign -------------------------------------------------------------------
& "$BT\zipalign.exe" -f -p 4 (Join-Path $repo 'out\base.apk') (Join-Path $repo 'out\aligned.apk')
if ($LASTEXITCODE -ne 0) { throw "zipalign failed" }
$ks = Join-Path $repo 'freemytv.keystore'
if (-not (Test-Path $ks)) {
    & $KEYTOOL -genkeypair -keystore $ks -alias freemytv -keyalg RSA -keysize 2048 -validity 20000 `
        -storepass freemytv -keypass freemytv -dname "CN=Free My TV" 2>&1 | Out-Null
}
& "$BT\apksigner.bat" sign --ks $ks --ks-pass pass:freemytv --key-pass pass:freemytv `
    --out (Join-Path $repo 'FreeMyTV.apk') (Join-Path $repo 'out\aligned.apk')
if ($LASTEXITCODE -ne 0) { throw "apksigner failed" }

$apk = Join-Path $repo 'FreeMyTV.apk'
"BUILT: $apk ({0:N2} MB)" -f ((Get-Item $apk).Length / 1MB)
& "$BT\apksigner.bat" verify --print-certs $apk | Select-Object -First 4
